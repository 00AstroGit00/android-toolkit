#!/data/data/com.termux/files/usr/bin/bash
#
# export.sh — Report export module
#
# Exports device reports in multiple formats:
#   - Markdown (.md)
#   - JSON (.json)
#   - CSV (.csv)
#   - HTML (.html)
#   - PDF (.pdf — via pandoc if available)
#   - ZIP archive (.zip) bundling all reports + logs
#
# Part of the Android Toolkit.

EXPORT_DIR="${ANDROID_TOOLKIT_ROOT_DIR}/exports"

##############################################
# Ensure export directory exists.
##############################################
export_init() {
    mkdir -p "$EXPORT_DIR"
}

##############################################
# Collect all report data into associative arrays.
##############################################
_export_collect_data() {
    local -n _data=$1

    # Device info
    _data["device_manufacturer"]="${CAP_MANUFACTURER:-unknown}"
    _data["device_model"]="${CAP_MODEL:-unknown}"
    _data["android_version"]="${CAP_ANDROID_VERSION:-unknown}"
    _data["android_sdk"]="${CAP_ANDROID_SDK:-unknown}"
    _data["one_ui_version"]="${CAP_ONE_UI_VERSION:-unknown}"
    _data["kernel"]="${CAP_KERNEL:-unknown}"
    _data["abi"]="${CAP_ABI:-unknown}"
    _data["backend"]="${ANDROID_TOOLKIT_BACKEND:-unknown}"
    _data["oem"]="${OEM_LOADED:-generic}"
    _data["version"]="${ANDROID_TOOLKIT_VERSION}"
    _data["date"]="$(date -Iseconds 2>/dev/null || date '+%Y-%m-%dT%H:%M:%S%z')"

    # Capabilities summary
    _data["capabilities"]="$(cap_list 2>/dev/null | paste -sd ';' || echo 'none')"

    # Log file
    _data["log_file"]="${LOG_FILE:-unknown}"
}

##############################################
# Export report in Markdown format.
# Arguments:
#   $1: output file path (optional)
##############################################
export_markdown() {
    local output="${1:-${EXPORT_DIR}/report.md}"
    export_init

    declare -A data
    _export_collect_data data

    cat > "$output" << EOF
# Android Toolkit Report

**Generated:** ${data[date]}  
**Toolkit Version:** ${data[version]}  
**Device:** ${data[device_manufacturer]} ${data[device_model]}  
**Android:** ${data[android_version]} (SDK ${data[android_sdk]})  
**Kernel:** ${data[kernel]}  
**OEM:** ${data[oem]}  
**Backend:** ${data[backend]}

## Device Information

| Property | Value |
|----------|-------|
| Manufacturer | ${data[device_manufacturer]} |
| Model | ${data[device_model]} |
| Android Version | ${data[android_version]} |
| SDK Level | ${data[android_sdk]} |
| One UI Version | ${data[one_ui_version]} |
| Kernel | ${data[kernel]} |
| ABI | ${data[abi]} |

## Diagnostics

Full diagnostics output available via \`toolkit.sh --doctor\`.

## Logs

Main log: \`${data[log_file]}\`

---

*Report generated by Android Toolkit v${data[version]}*
EOF

    log_success "Markdown report: $output"
    echo "$output"
}

##############################################
# Export report in JSON format.
# Arguments:
#   $1: output file path (optional)
##############################################
export_json() {
    local output="${1:-${EXPORT_DIR}/report.json}"
    export_init

    declare -A data
    _export_collect_data data

    if command -v jq &>/dev/null; then
        jq -n \
            --arg date "${data[date]}" \
            --arg version "${data[version]}" \
            --arg man "${data[device_manufacturer]}" \
            --arg model "${data[device_model]}" \
            --arg av "${data[android_version]}" \
            --arg sdk "${data[android_sdk]}" \
            --arg oui "${data[one_ui_version]}" \
            --arg kernel "${data[kernel]}" \
            --arg abi "${data[abi]}" \
            --arg backend "${data[backend]}" \
            --arg oem "${data[oem]}" \
            --arg caps "${data[capabilities]}" \
            --arg log "${data[log_file]}" \
            '{
                report: {
                    generated: $date,
                    toolkit_version: $version,
                    device: {
                        manufacturer: $man,
                        model: $model,
                        android_version: $av,
                        android_sdk: $sdk,
                        one_ui_version: $oui,
                        kernel: $kernel,
                        abi: $abi
                    },
                    runtime: {
                        backend: $backend,
                        oem: $oem
                    },
                    capabilities: $caps | split(";"),
                    log_file: $log
                }
            }' > "$output" 2>/dev/null
    else
        # Fallback without jq
        cat > "$output" << JSONEOF
{
  "report": {
    "generated": "${data[date]}",
    "toolkit_version": "${data[version]}",
    "device": {
      "manufacturer": "${data[device_manufacturer]}",
      "model": "${data[device_model]}",
      "android_version": "${data[android_version]}",
      "android_sdk": "${data[android_sdk]}",
      "one_ui_version": "${data[one_ui_version]}",
      "kernel": "${data[kernel]}",
      "abi": "${data[abi]}"
    },
    "runtime": {
      "backend": "${data[backend]}",
      "oem": "${data[oem]}"
    },
    "log_file": "${data[log_file]}"
  }
}
JSONEOF
    fi

    log_success "JSON report: $output"
    echo "$output"
}

##############################################
# Export report in CSV format.
# Arguments:
#   $1: output file path (optional)
##############################################
export_csv() {
    local output="${1:-${EXPORT_DIR}/report.csv}"
    export_init

    declare -A data
    _export_collect_data data

    {
        echo "Section,Property,Value"
        echo "Device,Manufacturer,${data[device_manufacturer]}"
        echo "Device,Model,${data[device_model]}"
        echo "Device,Android Version,${data[android_version]}"
        echo "Device,SDK Level,${data[android_sdk]}"
        echo "Device,One UI Version,${data[one_ui_version]}"
        echo "Device,Kernel,${data[kernel]}"
        echo "Device,ABI,${data[abi]}"
        echo "Runtime,Backend,${data[backend]}"
        echo "Runtime,OEM,${data[oem]}"
        echo "Runtime,Log File,${data[log_file]}"
    } > "$output"

    log_success "CSV report: $output"
    echo "$output"
}

