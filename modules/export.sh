    echo "$output"
}

##############################################
# Export report as PDF (via pandoc if available).
# Arguments:
#   $1: output file path (optional)
##############################################
export_pdf() {
    local output="${1:-${EXPORT_DIR}/report.pdf}"

    if command -v pandoc &>/dev/null; then
        local md_file
        md_file="$(export_markdown "${EXPORT_DIR}/.tmp_report.md")"
        if pandoc "$md_file" -o "$output" 2>/dev/null; then
            rm -f "$md_file"
            log_success "PDF report: $output"
            echo "$output"
        else
            rm -f "$md_file"
            log_error "PDF generation failed (pandoc error)"
            return 1
        fi
    else
        log_warning "pandoc not available — cannot generate PDF"
        log_info "Install pandoc: pkg install pandoc"
        log_info "Falling back to HTML..."
        export_html "$output"  # Return HTML path as fallback
    fi
}

##############################################
# Create a ZIP archive with all reports and logs.
# Arguments:
#   $1: output file path (optional)
##############################################
export_zip() {
    local timestamp
    timestamp="$(date '+%Y%m%d_%H%M%S')"
    local output="${1:-${EXPORT_DIR}/android-toolkit-report-${timestamp}.zip}"

    export_init

    # Generate all report formats
    local md_file json_file csv_file html_file
    md_file="$(export_markdown "${EXPORT_DIR}/.export_report.md")"
    json_file="$(export_json "${EXPORT_DIR}/.export_report.json")"
    csv_file="$(export_csv "${EXPORT_DIR}/.export_report.csv")"
    html_file="$(export_html "${EXPORT_DIR}/.export_report.html")"

    # Collect logs
    local logs_to_include=()
    if [[ -n "$LOG_FILE" && -f "$LOG_FILE" ]]; then
        logs_to_include+=("$LOG_FILE")
    fi

    if command -v zip &>/dev/null; then
        (
            cd "$EXPORT_DIR" || return 1
            zip -j "$output" \
                ".export_report.md" \
                ".export_report.json" \
                ".export_report.csv" \
                ".export_report.html" \
                "${logs_to_include[@]}" \
                2>/dev/null
        )

        # Cleanup temp files
        rm -f "$md_file" "$json_file" "$csv_file" "$html_file"

        log_success "ZIP archive: $output"
        echo "$output"
    else
        log_warning "zip not available — cannot create archive"
        log_info "Install zip: pkg install zip"
        echo "$md_file"  # Return MD path as fallback
    fi
}

##############################################
# Main export entry point.
# Arguments:
#   $1: format (md|json|csv|html|pdf|zip)
##############################################
export_report() {
    local format="${1:-md}"

    log_section "Export Report"

    case "$format" in
        md|markdown)    export_markdown ;;
        json)           export_json ;;
        csv)            export_csv ;;
        html)           export_html ;;
        pdf)            export_pdf ;;
        zip|archive)    export_zip ;;
        *)
            log_error "Unknown format: $format"
            log_info "Supported formats: md, json, csv, html, pdf, zip"
            return 1
            ;;
    esac

    log_show_file
}
